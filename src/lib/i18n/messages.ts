/** English version of an engine message or report; Turkish pages get the text unchanged. */
export function localizeMessage(text: string, lang: Locale): string {
  if (lang === 'tr') return text;
  return text
    .split('\n')
    .map((line) => RULES.reduce((out, [pattern, replacement]) => out.replace(pattern, replacement), line))
    .join('\n');
}
